/**
 * Writes `src/fontsource-weights.ts`: the static weights Fontsource
 * publishes for each family the style gallery names (D145). A gallery
 * style's tokens file imports one `@fontsource/<family>/<weight>.css` per
 * weight it uses, and Fontsource has no file for a weight the family does
 * not ship (Bebas Neue is 400 only), so `styleGalleryFontWeights` snaps to
 * the weights listed here. It is generated: run it again after an import
 * brings in a new family, never edit the output.
 *
 *   node --experimental-strip-types bin/fontsource-weights.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  fontsourcePackage,
  parseStyleGallery,
  styleGalleryFamilies,
} from '../src/style-gallery.ts';
import { STYLE_GALLERY_FILE } from './import-style-gallery.ts';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, '../src/fontsource-weights.ts');

const slug = (family: string) =>
  fontsourcePackage(family).slice('@fontsource/'.length);

const catalog = parseStyleGallery(readFileSync(STYLE_GALLERY_FILE, 'utf8'));
const families = styleGalleryFamilies(catalog.entries);
const rows: string[] = [];
for (const family of families) {
  const response = await fetch(
    `https://api.fontsource.org/v1/fonts/${slug(family)}`,
  );
  if (!response.ok) {
    throw new Error(`Fontsource has no ${family} (${response.status}).`);
  }
  const { weights } = (await response.json()) as { weights: number[] };
  rows.push(
    `  ${JSON.stringify(family)}: [${[...weights].sort((a, b) => a - b).join(', ')}],`,
  );
}
writeFileSync(
  OUT,
  [
    '// Generated by bin/fontsource-weights.ts. Do not edit.',
    '',
    '/** The static weights Fontsource publishes for each gallery family. */',
    'export const FONTSOURCE_WEIGHTS: Readonly<Record<string, readonly number[]>> = {',
    ...rows,
    '};',
    '',
  ].join('\n'),
);
console.log(`fontsource weights: ${rows.length} families`);
